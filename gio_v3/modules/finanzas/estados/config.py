def get_categoria_subcategoria(descripcion: str, custom_kw: dict | None = None) -> tuple[str, str]:
    desc = descripcion.upper()
    if custom_kw:
        for kw, (cat, subcat) in custom_kw.items():
            if kw in desc:
                return cat, subcat
    for keyword, (cat, subcat) in CATEGORIAS.items():
        if keyword.upper() in desc:
            return cat, subcat
    return "OTROS", ""


# ALIMENTACION (legado) → SUPER / COMIDA_FUERA / CAFE/PAN. Lo usan la
# migración finanzas_separa_alimentacion_2026_09 (database.py) y el blindaje
# _corregir_alimentacion_split (routes.py) para que ambos decidan igual.
_ALIM_SUB_DIRECTO = {
    'Súper': ('SUPER', 'Súper'), 'Supermercado': ('SUPER', 'Súper'),
    'Víveres': ('SUPER', 'Súper'), 'Despensa': ('SUPER', 'Súper'),
    'Conveniencia': ('SUPER', 'Conveniencia'),
    'Restaurante': ('COMIDA_FUERA', 'Restaurante'),
    'Fast Food': ('COMIDA_FUERA', 'Fast Food'),
    'Delivery': ('COMIDA_FUERA', 'Delivery'),
    'Café': ('CAFE/PAN', 'Café'), 'Pan': ('CAFE/PAN', 'Pan'),
}


def split_alimentacion(subcategoria: str | None, texto: str | None = '') -> tuple[str, str]:
    """Nueva (categoria, subcategoria) para una fila ALIMENTACION: por su
    subcategoría si es conocida; si no, por las reglas de la descripción
    (o keyword); sin pista, comida fuera / Restaurante."""
    if (subcategoria or '') in _ALIM_SUB_DIRECTO:
        return _ALIM_SUB_DIRECTO[subcategoria]
    cat, sub = get_categoria_subcategoria(texto or '')
    if cat in ('SUPER', 'COMIDA_FUERA', 'CAFE/PAN'):
        return cat, sub
    return 'COMIDA_FUERA', 'Restaurante'
